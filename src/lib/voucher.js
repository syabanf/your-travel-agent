/** `wide` lays the page out in A4 landscape, for reports with many columns. */
export function printDocument(title, bodyHTML, { wide = false } = {}) {
  const w = window.open("", "_blank");
  if (!w) return;
  const page = wide ? "@page { size: A4 landscape; margin: 14mm; }" : "";
  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title><style>${STYLE}${page}</style></head><body><div class="wrap${wide ? " wide" : ""}">${bodyHTML}<div class="foot">Icon Holiday Travel · This document was generated by the Icon Holiday platform. For assistance contact your travel concierge.</div></div></body></html>`);
  w.document.close();
  w.focus();
  setTimeout(() => { try { w.print(); } catch { /* user can print manually */ } }, 350);
}

